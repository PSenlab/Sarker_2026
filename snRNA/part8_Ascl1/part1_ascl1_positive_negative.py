# SECTION 9 — GSEA: Reactome Pathways 2024
# ═══════════════════════════════════════════════════════════════════════════════

csv_path = res_dir / "wilcoxon_Ascl1_pos_vs_neg_female_hepatocytes.csv"
results_df = pd.read_csv(csv_path)
results_df = results_df.rename(columns={"names": "gene"})
results_df["gene"] = results_df["gene"].astype(str)

# Rank genes by the Wilcoxon z-score ("scores" column from scanpy).
# Small random jitter (N(0, 1e-6)) breaks ties — GSEA requires unique ranks,
# and many lowly-expressed genes share identical test statistics.
results_df["Score"] = results_df["scores"] + np.random.normal(0, 1e-6, len(results_df))

rnk = results_df[["gene", "Score"]].dropna().sort_values("Score", ascending=False)

# Convert to uppercase because Reactome uses human gene symbols (uppercase),
# while the mouse data uses Title Case (e.g., Ascl1 → ASCL1).
rnk["gene"] = rnk["gene"].str.upper()

print(f"[INFO] Ranked {len(rnk)} genes for GSEA.")
print(rnk.head())

# Reactome_Pathways_2024 — curated biological pathways from reactome.org.
# min_size=2 allows even small pathways (important for specialized liver functions).
# max_size=2000 includes broad pathways like "Metabolism".
# 1000 permutations balances statistical accuracy with runtime (~2-5 min).
# seed=42 ensures reproducibility across runs.
try:
    gsea_results = gp.prerank(
        rnk=rnk,
        gene_sets="Reactome_Pathways_2024",
        permutation_num=1000,
        min_size=2,
        max_size=2000,
        seed=42,
        outdir=None,
        verbose=True,
    )
    print("[INFO] GSEA (Reactome_Pathways_2024) completed successfully.")
except Exception as e:
    print(f"[ERROR] GSEA failed: {e}")
    raise SystemExit

gsea_df = gsea_results.res2d.copy()

gsea_df["FDR q-val"] = pd.to_numeric(gsea_df["FDR q-val"], errors="coerce")
if "Gene %" in gsea_df.columns:
    gsea_df["Gene %"] = (
        gsea_df["Gene %"].astype(str)
        .str.replace("%", "", regex=False)
        .astype(float)
    )
else:
    gsea_df["Gene %"] = 1.0

print(f"[INFO] GSEA result table shape: {gsea_df.shape}")
print(gsea_df.head())

out_file = res_dir / "GSEA_Ascl1_pos_neg_female_hepatocytes_Reactome2024.csv"
gsea_df.to_csv(out_file, index=False)
print(f"[INFO] Saved {len(gsea_df)} pathways → {out_file}")
print("✅ GSEA completed successfully.")


