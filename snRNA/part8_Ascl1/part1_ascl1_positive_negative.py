# ═══════════════════════════════════════════════════════════════════════════════
# SECTION 7 — Differential Expression: Ascl1+ vs Ascl1− (Wilcoxon)
# ═══════════════════════════════════════════════════════════════════════════════

assert "Ascl1" in adata_fh.var_names, "Ascl1 not found in var_names"

print("\n" + "=" * 60)
print("DIFFERENTIAL EXPRESSION: Ascl1+ vs Ascl1- (Female Hepatocytes)")
print("=" * 60)

ascl1_expr = adata_fh[:, "Ascl1"].X.toarray().ravel()
adata_fh.obs["Ascl1_status"] = pd.Categorical(
    np.where(ascl1_expr > 0, "Ascl1_pos", "Ascl1_neg"),
    categories=["Ascl1_pos", "Ascl1_neg"],
    ordered=True,
)

print(f"\n📊 Group Sizes:")
print(adata_fh.obs["Ascl1_status"].value_counts())
print(f"\nAscl1-positive fraction: {(ascl1_expr > 0).mean():.3f} "
      f"({100 * (ascl1_expr > 0).mean():.1f}%)")

# Wilcoxon rank-sum test — a non-parametric test chosen because single-cell
# expression data is zero-inflated and non-normally distributed.
# use_raw=False → uses the normalized/log-transformed counts in adata.X
print("\n🚀 Running Wilcoxon DE test (Ascl1_pos vs Ascl1_neg) …")
sc.tl.rank_genes_groups(
    adata_fh,
    groupby="Ascl1_status",
    groups=["Ascl1_pos"],       # test group
    reference="Ascl1_neg",      # reference group
    method="wilcoxon",          # non-parametric rank-sum
    use_raw=False,              # use normalized expression in .X
)
print("✔️ DE test complete.")

sc.pl.rank_genes_groups(adata_fh, n_genes=20, sharey=False)

de_res = sc.get.rank_genes_groups_df(adata_fh, group="Ascl1_pos")

# Benjamini-Hochberg adjusted p-value < 0.05 is the standard threshold
# for controlling the false discovery rate in genome-wide tests.
pval_threshold = 0.05

sig_genes  = de_res[de_res["pvals_adj"] < pval_threshold]
up_genes   = sig_genes[sig_genes["logfoldchanges"] > 0]
down_genes = sig_genes[sig_genes["logfoldchanges"] < 0]

print("\n" + "=" * 60)
print("DE RESULTS SUMMARY")
print("=" * 60)
print(f"\n📊 Overall DE Statistics:")
print(f"   Total genes tested: {len(de_res):,}")
print(f"   Significant genes (adj p < {pval_threshold}): {len(sig_genes):,}")
print(f"   Upregulated in Ascl1+: {len(up_genes):,}")
print(f"   Downregulated in Ascl1+: {len(down_genes):,}")

print(f"\n📊 Top 15 Upregulated Genes (Ascl1+ vs Ascl1-):")
top_up = up_genes.nlargest(15, "scores")[["names", "scores", "logfoldchanges", "pvals_adj"]]
top_up.columns = ["Gene", "Score", "logFC", "adj_pval"]
print(top_up.to_string(index=False))

print(f"\n📊 Top 15 Downregulated Genes (Ascl1+ vs Ascl1-):")
top_down = down_genes.nsmallest(15, "scores")[["names", "scores", "logfoldchanges", "pvals_adj"]]
top_down.columns = ["Gene", "Score", "logFC", "adj_pval"]
print(top_down.to_string(index=False))

de_res.to_csv(res_dir / "wilcoxon_Ascl1_pos_vs_neg_female_hepatocytes.csv", index=False)
sig_genes.to_csv(res_dir / "wilcoxon_Ascl1_pos_vs_neg_female_hepatocytes_significant.csv", index=False)
