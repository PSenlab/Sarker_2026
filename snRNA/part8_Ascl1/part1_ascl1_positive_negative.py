# ═══════════════════════════════════════════════════════════════════════════════
# SECTION 1 — Load Data
# ═══════════════════════════════════════════════════════════════════════════════

# Path to the WNN-integrated single-cell RNA object (h5ad format).
# This object was generated by the ArchR preprocessing pipeline (Step 1)
# followed by schard h5ad conversion. It contains cells from 5 age groups
# across both sexes, with broad celltype and hepatocyte sub-classifications.
h5ad_path = "/data/sarkern2/multiome_liver/final_object/final_rna_wnn.h5ad"

# Output directories — created automatically if missing
fig_dir = Path("figures")
res_dir = Path("results")
fig_dir.mkdir(exist_ok=True)
res_dir.mkdir(exist_ok=True)

print("Loading data …")
adata = sc.read_h5ad(h5ad_path)
print(f"Loaded {adata.n_obs:,} cells × {adata.n_vars:,} genes")


# ═══════════════════════════════════════════════════════════════════════════════
# SECTION 2 — Global Ascl1 Profiling (All Cells)
# ═══════════════════════════════════════════════════════════════════════════════

# Age groups are ordered biologically: young → mid_age → old → pre_geriatric → geriatric.
# This ordering ensures dot plots and summaries follow the aging trajectory.
age_order = ["young", "mid_age", "old", "pre_geriatric", "geriatric"]
age_order_filtered = [a for a in age_order if a in adata.obs["age"].unique()]
adata.obs["age"] = adata.obs["age"].astype(
    pd.CategoricalDtype(categories=age_order_filtered, ordered=True)
)

# Extract Ascl1 normalized expression.
# Cells with expression > 0 are classified as Ascl1-positive (Ascl1+).
gene = "Ascl1"
expr = adata[:, gene].X
expr = expr.toarray().ravel() if not isinstance(expr, np.ndarray) else expr.ravel()
adata.obs["Ascl1_expr"] = expr
adata.obs["Ascl1_positive"] = adata.obs["Ascl1_expr"] > 0

# ── Summary statistics ───────────────────────────────────────────────────────
print("=" * 60)
print("ASCL1 EXPRESSION SUMMARY")
print("=" * 60)

total_cells = adata.n_obs
ascl1_pos = adata.obs["Ascl1_positive"].sum()
print(f"\n📊 Overall:")
print(f"   Total cells: {total_cells:,}")
print(f"   Ascl1+ cells: {ascl1_pos:,} ({100 * ascl1_pos / total_cells:.1f}%)")

print(f"\n📊 By Sex:")
sex_summary = adata.obs.groupby("sex").agg(
    total=("Ascl1_positive", "size"),
    positive=("Ascl1_positive", "sum"),
    mean_expr=("Ascl1_expr", "mean"),
).reset_index()
sex_summary["pct_positive"] = 100 * sex_summary["positive"] / sex_summary["total"]
print(sex_summary.to_string(index=False))

print(f"\n📊 By Age:")
age_summary = adata.obs.groupby("age", observed=True).agg(
    total=("Ascl1_positive", "size"),
    positive=("Ascl1_positive", "sum"),
    mean_expr=("Ascl1_expr", "mean"),
).reset_index()
age_summary["pct_positive"] = 100 * age_summary["positive"] / age_summary["total"]
print(age_summary.to_string(index=False))

print(f"\n📊 By Celltype:")
ct_summary = adata.obs.groupby("celltype", observed=True).agg(
    total=("Ascl1_positive", "size"),
    positive=("Ascl1_positive", "sum"),
    mean_expr=("Ascl1_expr", "mean"),
).reset_index()
ct_summary["pct_positive"] = 100 * ct_summary["positive"] / ct_summary["total"]
ct_summary = ct_summary.sort_values("pct_positive", ascending=False)
print(ct_summary.to_string(index=False))

print(f"\n📊 By Sex × Age:")
sex_age_summary = adata.obs.groupby(["sex", "age"], observed=True).agg(
    total=("Ascl1_positive", "size"),
    positive=("Ascl1_positive", "sum"),
    mean_expr=("Ascl1_expr", "mean"),
).reset_index()
sex_age_summary["pct_positive"] = 100 * sex_age_summary["positive"] / sex_age_summary["total"]
print(sex_age_summary.to_string(index=False))
print("\n" + "=" * 60)

# ── 3-panel dot plot: Sex → Age → Celltype ───────────────────────────────────
fig, axes = plt.subplots(1, 3, figsize=(13, 4))

sc.pl.dotplot(adata, var_names=["Ascl1"], groupby="sex",
              ax=axes[0], show=False, cmap="Reds")
axes[0].set_title("Ascl1 by Sex")

sc.pl.dotplot(adata, var_names=["Ascl1"], groupby="age",
              ax=axes[1], show=False, cmap="Reds")
axes[1].set_title("Ascl1 by Age (Male and Female)")

sc.pl.dotplot(adata, var_names=["Ascl1"], groupby="celltype",
              ax=axes[2], show=False, cmap="Reds")
axes[2].set_title("Ascl1 by Celltype - Male and Female")

plt.tight_layout()
plt.savefig(fig_dir / "Ascl1_dotplots_all_sex_age_celltype.pdf",
            dpi=300, bbox_inches="tight")
plt.show()
print(f"Saved: {fig_dir}/Ascl1_dotplots_all_sex_age_celltype.pdf")

# ── Save CSVs ────────────────────────────────────────────────────────────────
sex_summary.to_csv(res_dir / "Ascl1_summary_by_sex.csv", index=False)
age_summary.to_csv(res_dir / "Ascl1_summary_by_age.csv", index=False)
ct_summary.to_csv(res_dir / "Ascl1_summary_by_celltype.csv", index=False)
