"""
ascl1_liver_aging_analysis.py
==============================
Ascl1 expression analysis in murine liver aging (single-cell multiome RNA).

Sections
--------
1. Load data
2. Global Ascl1 profiling (sex / age / celltype)
3. Female-only Ascl1 analysis
4. Female hepatocyte Ascl1 analysis (age / celltype2)
5. Count-based dot plots (Seaborn)
6. Ascl1+ subset deep characterization
7. Differential expression — Ascl1+ vs Ascl1− (Wilcoxon)
8. Volcano plot with functional gene annotations
9. GSEA — Reactome Pathways 2024
10. GSEA dot plot
"""

